export const translations = { ca, es, en }

/** Interpolació mínima `{{var}}` — sense dependències externes. */
export function interpolate(str, vars) {
  if (!vars) return str
  return str.replace(/\{\{(\w+)\}\}/g, (match, key) => (key in vars ? String(vars[key]) : match))
}

export function translate(language, key, vars) {
  const dict = translations[language] ?? translations[DEFAULT_LANGUAGE]
  const raw = dict[key] ?? translations[DEFAULT_LANGUAGE][key] ?? key
  return interpolate(raw, vars)
}
